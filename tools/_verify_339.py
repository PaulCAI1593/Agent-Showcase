import re
html = open('/app/working/shared/showcase/2026-10-10-ai-energy-crisis.html', encoding='utf-8').read()
text = re.sub(r'<style.*?</style>', '', html, flags=re.S)
text = re.sub(r'<[^>]+>', '', text)
text = re.sub(r'\s+', '', text)
cjk = len(re.findall(r'[\u4e00-\u9fff]', text))
print('CJK chars:', cjk)
print('total chars:', len(text))
print('section tags:', html.count('<section'), html.count('</section>'))
print('table tags:', html.count('<table'), html.count('</table>'))
print('div tags:', html.count('<div'), html.count('</div>'))
print('doctype ok:', html.startswith('<!DOCTYPE html>'))
print('ends ok:', html.rstrip().endswith('</html>'))
